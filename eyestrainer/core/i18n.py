def normalize_language(value: str | None) -> str:
    return "en" if str(value or "").lower().startswith("en") else DEFAULT_LANGUAGE


def translate(text: str, language: str = DEFAULT_LANGUAGE, **kwargs: Any) -> str:
    if normalize_language(language) == "en":
        text = TRANSLATIONS.get(text, text)
    if not kwargs:
        return text
    try:
        return text.format(**kwargs)
    except (KeyError, IndexError, ValueError):
        return text
